package com.billingsystem.billing_system;

import java.util.Optional;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.web.servlet.MockMvc;

import static org.junit.jupiter.api.Assertions.*;
import static org.springframework.security.test.web.servlet.request.SecurityMockMvcRequestPostProcessors.csrf;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest(properties = {
        "spring.datasource.url=jdbc:h2:mem:billing-reset-tests;DB_CLOSE_DELAY=-1",
        "app.auth.owner-password=TestOwnerPassword#2026",
        "app.auth.cashier-password=TestCashierPassword#2026",
        "app.auth.customer-password=TestCustomerPassword#2026"
})
@AutoConfigureMockMvc
public class PasswordResetTests {

    @Autowired
    private PasswordResetService passwordResetService;

    @Autowired
    private EmailService emailService;

    @Autowired
    private JdbcTemplate jdbc;

    @Autowired
    private PasswordEncoder passwordEncoder;

    @Autowired
    private MockMvc mockMvc;

    @BeforeEach
    void setupTestData() {
        emailService.clearLastSentEmail();
        // Ensure reset table exists
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS password_reset_tokens (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    token VARCHAR(100) NOT NULL UNIQUE,
                    username VARCHAR(80) NOT NULL,
                    email VARCHAR(254) NOT NULL,
                    expiry_time TIMESTAMP NOT NULL,
                    used BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT fk_reset_token_user FOREIGN KEY (username) REFERENCES app_users(username)
                )
                """);

        // Ensure a known test user exists
        jdbc.update("DELETE FROM password_reset_tokens WHERE username = 'reset_test_user'");
        jdbc.update("DELETE FROM app_users WHERE username = 'reset_test_user'");

        jdbc.update("""
                INSERT INTO app_users (username, password_hash, role, display_name, email, phone, enabled)
                VALUES ('reset_test_user', ?, 'CUSTOMER', 'Reset Test User', 'testuser@freshledger.local', '+91 99999 88888', TRUE)
                """, passwordEncoder.encode("InitialPassword#123"));
    }

    @Test
    void testInitiatePasswordResetSuccess() {
        PasswordResetService.ResetRequestResult result = passwordResetService.initiatePasswordReset(
                "testuser@freshledger.local", "http://localhost:8080");

        assertTrue(result.success());
        assertNotNull(result.token());
        assertNotNull(result.verificationLink());
        assertTrue(result.verificationLink().contains("http://localhost:8080/reset-password?token="));

        // Verify email service recorded the link
        EmailService.SentEmail sentEmail = emailService.getLastSentEmail();
        assertNotNull(sentEmail);
        assertEquals("testuser@freshledger.local", sentEmail.toEmail());
        assertEquals("Reset Test User", sentEmail.recipientName());
        assertEquals(result.verificationLink(), sentEmail.resetLink());
    }

    @Test
    void testInitiatePasswordResetUnregisteredEmail() {
        PasswordResetService.ResetRequestResult result = passwordResetService.initiatePasswordReset(
                "doesnotexist@nowhere.com", "http://localhost:8080");

        assertFalse(result.success());
        assertNull(result.token());
        assertNull(emailService.getLastSentEmail());
    }

    @Test
    void testValidateTokenLifecycle() {
        PasswordResetService.ResetRequestResult req = passwordResetService.initiatePasswordReset(
                "testuser@freshledger.local", "http://localhost:8080");
        String token = req.token();

        // Token should be valid
        Optional<PasswordResetService.ResetTokenDetails> detailsOpt = passwordResetService.validateToken(token);
        assertTrue(detailsOpt.isPresent());
        assertEquals("reset_test_user", detailsOpt.get().username());
        assertEquals("testuser@freshledger.local", detailsOpt.get().email());
        assertFalse(detailsOpt.get().used());

        // Invalid token should fail
        Optional<PasswordResetService.ResetTokenDetails> invalidOpt = passwordResetService.validateToken("fake-token-12345");
        assertTrue(invalidOpt.isEmpty());
    }

    @Test
    void testCompletePasswordResetSuccessAndSingleUse() {
        PasswordResetService.ResetRequestResult req = passwordResetService.initiatePasswordReset(
                "testuser@freshledger.local", "http://localhost:8080");
        String token = req.token();

        String newPassword = "BrandNewSecurePassword#2026";
        PasswordResetService.ResetCompletionResult completionResult = passwordResetService.completePasswordReset(
                token, newPassword, newPassword);

        assertTrue(completionResult.success());

        // Verify password hash in database changed and matches new password
        String updatedHash = jdbc.queryForObject("SELECT password_hash FROM app_users WHERE username = 'reset_test_user'",
                String.class);
        assertNotNull(updatedHash);
        assertTrue(passwordEncoder.matches(newPassword, updatedHash));

        // Verify token is now marked used and cannot be reused
        Optional<PasswordResetService.ResetTokenDetails> afterUse = passwordResetService.validateToken(token);
        assertTrue(afterUse.isEmpty(), "Token should no longer be valid after being used");

        PasswordResetService.ResetCompletionResult secondAttempt = passwordResetService.completePasswordReset(
                token, "AnotherPassword#2026", "AnotherPassword#2026");
        assertFalse(secondAttempt.success(), "Second reset attempt with same token must fail");
    }

    @Test
    void testPasswordResetValidationRules() {
        PasswordResetService.ResetRequestResult req = passwordResetService.initiatePasswordReset(
                "testuser@freshledger.local", "http://localhost:8080");
        String token = req.token();

        // Mismatched passwords
        PasswordResetService.ResetCompletionResult mismatch = passwordResetService.completePasswordReset(
                token, "ValidPassword#123", "MismatchPassword#123");
        assertFalse(mismatch.success());
        assertTrue(mismatch.message().contains("do not match"));

        // Too short (< 12 chars)
        PasswordResetService.ResetCompletionResult tooShort = passwordResetService.completePasswordReset(
                token, "Short#1", "Short#1");
        assertFalse(tooShort.success());
        assertTrue(tooShort.message().contains("12"));
    }

    @Test
    void testMockMvcForgotPasswordAndResetFlow() throws Exception {
        // 1. GET /forgot-password should return 200 OK
        mockMvc.perform(get("/forgot-password"))
                .andExpect(status().isOk())
                .andExpect(view().name("forgot-password"));

        // 2. POST /forgot-password with valid email
        mockMvc.perform(post("/forgot-password")
                        .with(csrf())
                        .param("email", "testuser@freshledger.local"))
                .andExpect(status().isOk())
                .andExpect(view().name("forgot-password"))
                .andExpect(model().attribute("requestSent", true))
                .andExpect(model().attributeExists("verificationLink"));

        // Retrieve token from last sent email
        EmailService.SentEmail sent = emailService.getLastSentEmail();
        assertNotNull(sent);
        String resetUrl = sent.resetLink();
        String token = resetUrl.substring(resetUrl.indexOf("token=") + 6);

        // 3. GET /reset-password with valid token
        mockMvc.perform(get("/reset-password").param("token", token))
                .andExpect(status().isOk())
                .andExpect(view().name("reset-password"))
                .andExpect(model().attribute("invalidToken", false))
                .andExpect(model().attribute("username", "reset_test_user"));

        // 4. POST /reset-password
        mockMvc.perform(post("/reset-password")
                        .with(csrf())
                        .param("token", token)
                        .param("newPassword", "MvcUpdatedPass#2026")
                        .param("confirmPassword", "MvcUpdatedPass#2026"))
                .andExpect(status().is3xxRedirection())
                .andExpect(redirectedUrl("/login?resetSuccess"));

        // 5. User can authenticate with the newly set password
        String updatedHash = jdbc.queryForObject("SELECT password_hash FROM app_users WHERE username = 'reset_test_user'",
                String.class);
        assertTrue(passwordEncoder.matches("MvcUpdatedPass#2026", updatedHash));
    }
}
