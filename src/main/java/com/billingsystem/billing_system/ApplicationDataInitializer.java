package com.billingsystem.billing_system;

import java.nio.charset.StandardCharsets;
import java.util.List;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.CommandLineRunner;
import org.springframework.context.annotation.Profile;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Component;

@Component
@Profile("dev")
public class ApplicationDataInitializer implements CommandLineRunner {
    private final JdbcTemplate jdbc;
    private final PasswordEncoder passwordEncoder;
    private final String ownerPassword;
    private final String cashierPassword;
    private final String customerPassword;

    public ApplicationDataInitializer(
            JdbcTemplate jdbc,
            PasswordEncoder passwordEncoder,
            @Value("${app.auth.owner-password}") String ownerPassword,
            @Value("${app.auth.cashier-password}") String cashierPassword,
            @Value("${app.auth.customer-password}") String customerPassword) {
        this.jdbc = jdbc;
        this.passwordEncoder = passwordEncoder;
        this.ownerPassword = ownerPassword;
        this.cashierPassword = cashierPassword;
        this.customerPassword = customerPassword;
        if (List.of(ownerPassword, cashierPassword, customerPassword).stream()
                .anyMatch(password -> password.length() < 12
                        || password.getBytes(StandardCharsets.UTF_8).length > 72)) {
            throw new IllegalStateException("All APP_AUTH_* passwords must be 12 to 72 UTF-8 bytes long.");
        }
    }

    @Override
    public void run(String... args) {
        try {
            Integer hasOldColumn = jdbc.queryForObject(
                    "SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'PASSWORD_RESET_TOKENS' AND COLUMN_NAME = 'TOKEN_HASH'",
                    Integer.class);
            if (hasOldColumn != null && hasOldColumn > 0) {
                jdbc.execute("DROP TABLE password_reset_tokens");
            }
        } catch (Exception ignored) {}

        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS password_reset_tokens (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    token VARCHAR(100) NOT NULL UNIQUE,
                    username VARCHAR(80) NOT NULL,
                    email VARCHAR(254) NOT NULL,
                    expiry_time TIMESTAMP NOT NULL,
                    used BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT fk_reset_token_user FOREIGN KEY (username) REFERENCES app_users(username)
                )
                """);

        syncSeededUser("owner", ownerPassword, "OWNER", "Store Owner", "owner@freshledger.local", null, 0);
        syncSeededUser("cashier", cashierPassword, "CASHIER", "Store Cashier", "cashier@freshledger.local", null, 0);
        syncSeededUser("customer", customerPassword, "CUSTOMER", "Sample Customer",
                "customer@freshledger.local", "+91 98765 43210", 1250);
        List<ProductImage> missingImages = jdbc.query("SELECT id, name, category FROM products WHERE image_path IS NULL",
                (rs, row) -> new ProductImage(rs.getLong("id"), rs.getString("name"), rs.getString("category")));
        for (ProductImage product : missingImages) {
            jdbc.update("UPDATE products SET image_path = ? WHERE id = ? AND image_path IS NULL",
                    ProductImageLibrary.match(product.name(), product.category()), product.id());
        }
    }

    private void syncSeededUser(String username, String rawPassword, String role, String displayName,
                                String email, String phone, int loyaltyPoints) {
        Integer existing = jdbc.queryForObject("SELECT COUNT(*) FROM app_users WHERE username = ?",
                Integer.class, username);
        if (existing == null || existing == 0) {
            jdbc.update("""
                    INSERT INTO app_users (username, password_hash, role, display_name, email, phone, loyalty_points)
                    VALUES (?, ?, ?, ?, ?, ?, ?)
                    """, username, passwordEncoder.encode(rawPassword), role, displayName, email, phone, loyaltyPoints);
        } else {
            jdbc.update("UPDATE app_users SET password_hash = ?, email = COALESCE(email, ?) WHERE username = ? AND role = ?",
                    passwordEncoder.encode(rawPassword), email, username, role);
        }
    }

    private record ProductImage(long id, String name, String category) {}
}
