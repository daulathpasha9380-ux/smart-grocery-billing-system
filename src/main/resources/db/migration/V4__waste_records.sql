CREATE TABLE waste_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    actor_username VARCHAR(80) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_cost DECIMAL(12, 2) NOT NULL,
    reason VARCHAR(40) NOT NULL,
    notes VARCHAR(500) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_waste_records_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_waste_records_actor FOREIGN KEY (actor_username) REFERENCES app_users(username),
    CONSTRAINT ck_waste_records_quantity CHECK (quantity > 0),
    CONSTRAINT ck_waste_records_cost CHECK (unit_cost >= 0)
);

CREATE INDEX idx_waste_records_created_at ON waste_records(created_at);