CREATE TABLE refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id VARCHAR(80) NOT NULL UNIQUE,
    refund_reference VARCHAR(80) NOT NULL UNIQUE,
    transaction_id BIGINT NOT NULL,
    approved_by VARCHAR(80) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    amount DECIMAL(12, 2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_refunds_transaction FOREIGN KEY (transaction_id) REFERENCES transactions(id),
    CONSTRAINT fk_refunds_approver FOREIGN KEY (approved_by) REFERENCES app_users(username),
    CONSTRAINT ck_refunds_amount CHECK (amount >= 0)
);

CREATE TABLE refund_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id BIGINT NOT NULL,
    original_item_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    refund_amount DECIMAL(12, 2) NOT NULL,
    restocked BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_refund_items_refund FOREIGN KEY (refund_id) REFERENCES refunds(id),
    CONSTRAINT fk_refund_items_original FOREIGN KEY (original_item_id) REFERENCES transaction_items(id),
    CONSTRAINT fk_refund_items_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT uq_refund_items_line UNIQUE (refund_id, original_item_id),
    CONSTRAINT ck_refund_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_refund_items_amount CHECK (refund_amount >= 0)
);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    actor_username VARCHAR(80) NOT NULL,
    movement_type VARCHAR(20) NOT NULL,
    quantity_change INTEGER NOT NULL,
    reference_invoice VARCHAR(80),
    reason VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_stock_movements_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_stock_movements_actor FOREIGN KEY (actor_username) REFERENCES app_users(username),
    CONSTRAINT ck_stock_movements_quantity CHECK (quantity_change <> 0)
);

CREATE INDEX idx_refunds_transaction ON refunds(transaction_id, created_at);
CREATE INDEX idx_refund_items_original ON refund_items(original_item_id);
CREATE INDEX idx_stock_movements_product ON stock_movements(product_id, created_at);