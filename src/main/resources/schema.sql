CREATE TABLE IF NOT EXISTS app_users (
    username VARCHAR(80) PRIMARY KEY,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    display_name VARCHAR(160) NOT NULL,
    email VARCHAR(254),
    phone VARCHAR(30),
    loyalty_points INTEGER NOT NULL DEFAULT 0,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_app_users_email UNIQUE (email)
);

ALTER TABLE app_users ADD COLUMN IF NOT EXISTS enabled BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    category VARCHAR(80) NOT NULL,
    brand VARCHAR(100) NOT NULL,
    barcode VARCHAR(80) NOT NULL,
    purchase_price DECIMAL(12, 2) NOT NULL,
    price DECIMAL(12, 2) NOT NULL,
    stock INTEGER NOT NULL,
    min_stock INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_products_barcode UNIQUE (barcode),
    CONSTRAINT ck_products_prices CHECK (purchase_price >= 0 AND price >= 0),
    CONSTRAINT ck_products_stock CHECK (stock >= 0 AND min_stock >= 0)
);

ALTER TABLE products ADD COLUMN IF NOT EXISTS image_path VARCHAR(255);

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id VARCHAR(80) NOT NULL UNIQUE,
    invoice VARCHAR(80) NOT NULL UNIQUE,
    transaction_type VARCHAR(12) NOT NULL,
    customer_username VARCHAR(80),
    customer_name VARCHAR(160) NOT NULL,
    cashier_username VARCHAR(80) NOT NULL,
    payment_mode VARCHAR(40) NOT NULL,
    subtotal DECIMAL(12, 2) NOT NULL,
    discount DECIMAL(12, 2) NOT NULL,
    tax DECIMAL(12, 2) NOT NULL,
    total DECIMAL(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transaction_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_name VARCHAR(160) NOT NULL,
    unit_price DECIMAL(12, 2) NOT NULL,
    quantity INTEGER NOT NULL,
    line_total DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_transaction_items_transaction FOREIGN KEY (transaction_id) REFERENCES transactions(id),
    CONSTRAINT ck_transaction_items_quantity CHECK (quantity > 0)
);

CREATE INDEX IF NOT EXISTS idx_transactions_customer ON transactions(customer_username, created_at);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(100) NOT NULL UNIQUE,
    username VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL,
    expiry_time TIMESTAMP NOT NULL,
    used BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reset_token_user FOREIGN KEY (username) REFERENCES app_users(username)
);

ALTER TABLE password_reset_tokens ADD COLUMN IF NOT EXISTS used BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE password_reset_tokens ADD COLUMN IF NOT EXISTS expiry_time TIMESTAMP;
ALTER TABLE password_reset_tokens ADD COLUMN IF NOT EXISTS email VARCHAR(254);
ALTER TABLE password_reset_tokens ADD COLUMN IF NOT EXISTS token VARCHAR(100);
