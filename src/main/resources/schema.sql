CREATE TABLE IF NOT EXISTS app_users (
    username VARCHAR(80) PRIMARY KEY,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    display_name VARCHAR(160) NOT NULL,
    email VARCHAR(254),
    phone VARCHAR(30),
    loyalty_points INTEGER NOT NULL DEFAULT 0,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_app_users_email UNIQUE (email)
);

ALTER TABLE app_users ADD COLUMN IF NOT EXISTS enabled BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    token_hash CHAR(64) PRIMARY KEY,
    username VARCHAR(80) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_username
    ON password_reset_tokens(username, created_at);

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    category VARCHAR(80) NOT NULL,
    brand VARCHAR(100) NOT NULL,
    barcode VARCHAR(80) NOT NULL,
    purchase_price DECIMAL(12, 2) NOT NULL,
    price DECIMAL(12, 2) NOT NULL,
    stock INTEGER NOT NULL,
    min_stock INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_products_barcode UNIQUE (barcode),
    CONSTRAINT ck_products_prices CHECK (purchase_price >= 0 AND price >= 0),
    CONSTRAINT ck_products_stock CHECK (stock >= 0 AND min_stock >= 0)
);

ALTER TABLE products ADD COLUMN IF NOT EXISTS image_path VARCHAR(255);

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id VARCHAR(80) NOT NULL UNIQUE,
    invoice VARCHAR(80) NOT NULL UNIQUE,
    transaction_type VARCHAR(12) NOT NULL,
    customer_username VARCHAR(80),
    customer_name VARCHAR(160) NOT NULL,
    cashier_username VARCHAR(80) NOT NULL,
    payment_mode VARCHAR(40) NOT NULL,
    subtotal DECIMAL(12, 2) NOT NULL,
    discount DECIMAL(12, 2) NOT NULL,
    tax DECIMAL(12, 2) NOT NULL,
    total DECIMAL(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transaction_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_name VARCHAR(160) NOT NULL,
    unit_price DECIMAL(12, 2) NOT NULL,
    quantity INTEGER NOT NULL,
    line_total DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_transaction_items_transaction FOREIGN KEY (transaction_id) REFERENCES transactions(id),
    CONSTRAINT ck_transaction_items_quantity CHECK (quantity > 0)
);

CREATE TABLE IF NOT EXISTS refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id VARCHAR(80) NOT NULL UNIQUE,
    refund_reference VARCHAR(80) NOT NULL UNIQUE,
    transaction_id BIGINT NOT NULL,
    approved_by VARCHAR(80) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    amount DECIMAL(12, 2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_refunds_transaction FOREIGN KEY (transaction_id) REFERENCES transactions(id),
    CONSTRAINT fk_refunds_approver FOREIGN KEY (approved_by) REFERENCES app_users(username),
    CONSTRAINT ck_refunds_amount CHECK (amount >= 0)
);

CREATE TABLE IF NOT EXISTS refund_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id BIGINT NOT NULL,
    original_item_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    refund_amount DECIMAL(12, 2) NOT NULL,
    restocked BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_refund_items_refund FOREIGN KEY (refund_id) REFERENCES refunds(id),
    CONSTRAINT fk_refund_items_original FOREIGN KEY (original_item_id) REFERENCES transaction_items(id),
    CONSTRAINT fk_refund_items_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT uq_refund_items_line UNIQUE (refund_id, original_item_id),
    CONSTRAINT ck_refund_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_refund_items_amount CHECK (refund_amount >= 0)
);

CREATE TABLE IF NOT EXISTS stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    actor_username VARCHAR(80) NOT NULL,
    movement_type VARCHAR(20) NOT NULL,
    quantity_change INTEGER NOT NULL,
    reference_invoice VARCHAR(80),
    reason VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_stock_movements_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_stock_movements_actor FOREIGN KEY (actor_username) REFERENCES app_users(username),
    CONSTRAINT ck_stock_movements_quantity CHECK (quantity_change <> 0)
);

CREATE INDEX IF NOT EXISTS idx_refunds_transaction ON refunds(transaction_id, created_at);
CREATE INDEX IF NOT EXISTS idx_refund_items_original ON refund_items(original_item_id);
CREATE INDEX IF NOT EXISTS idx_stock_movements_product ON stock_movements(product_id, created_at);

CREATE TABLE IF NOT EXISTS waste_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    actor_username VARCHAR(80) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_cost DECIMAL(12, 2) NOT NULL,
    reason VARCHAR(40) NOT NULL,
    notes VARCHAR(500) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_waste_records_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_waste_records_actor FOREIGN KEY (actor_username) REFERENCES app_users(username),
    CONSTRAINT ck_waste_records_quantity CHECK (quantity > 0),
    CONSTRAINT ck_waste_records_cost CHECK (unit_cost >= 0)
);

CREATE INDEX IF NOT EXISTS idx_waste_records_created_at ON waste_records(created_at);

CREATE TABLE IF NOT EXISTS loyalty_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_key VARCHAR(120) NOT NULL UNIQUE,
    username VARCHAR(80) NOT NULL,
    transaction_id BIGINT NOT NULL,
    refund_id BIGINT,
    entry_type VARCHAR(32) NOT NULL,
    points_delta INTEGER NOT NULL,
    reason VARCHAR(200) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_loyalty_user FOREIGN KEY (username) REFERENCES app_users(username),
    CONSTRAINT fk_loyalty_transaction FOREIGN KEY (transaction_id) REFERENCES transactions(id),
    CONSTRAINT fk_loyalty_refund FOREIGN KEY (refund_id) REFERENCES refunds(id),
    CONSTRAINT ck_loyalty_entry_type CHECK (entry_type IN
        ('EARN', 'REDEEM', 'REFUND_EARN_REVERSAL', 'REFUND_REDEMPTION_RESTORE')),
    CONSTRAINT ck_loyalty_points_delta CHECK (points_delta <> 0)
);

CREATE INDEX IF NOT EXISTS idx_loyalty_transactions_user ON loyalty_transactions(username, created_at);
CREATE INDEX IF NOT EXISTS idx_loyalty_transactions_sale ON loyalty_transactions(transaction_id, entry_type);

CREATE INDEX IF NOT EXISTS idx_transactions_customer ON transactions(customer_username, created_at);
